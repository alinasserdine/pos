CREATE VIEW sales AS SELECT * FROM documents WHERE kind='SALE';

CREATE VIEW sale_items AS SELECT l.* FROM document_lines l JOIN documents d ON d.id=l.document_id WHERE d.kind='SALE';

CREATE VIEW sale_returns AS SELECT * FROM documents WHERE kind='SALE_RETURN';

CREATE VIEW purchases AS SELECT * FROM documents WHERE kind='PURCHASE';

CREATE VIEW purchase_returns AS SELECT * FROM documents WHERE kind='PURCHASE_RETURN';

CREATE VIEW customers AS SELECT * FROM parties WHERE kind='CUSTOMER';

CREATE VIEW suppliers AS SELECT * FROM parties WHERE kind='SUPPLIER';

CREATE VIEW v_sales_facts AS SELECT d.id AS document_id,d.document_date,d.kind,d.number,d.party_id,d.party_name,d.created_by,l.product_id,l.product_name,l.category_name,l.quantity*CASE WHEN d.kind='SALE' THEN 1 ELSE -1 END AS quantity,l.base_net*CASE WHEN d.kind='SALE' THEN 1 ELSE -1 END AS revenue,l.base_tax*CASE WHEN d.kind='SALE' THEN 1 ELSE -1 END AS tax,l.cost_total*CASE WHEN d.kind='SALE' THEN 1 ELSE -1 END AS cogs,l.discount*d.rate_to_base*CASE WHEN d.kind='SALE' THEN 1 ELSE -1 END AS discount FROM documents d JOIN document_lines l ON l.document_id=d.id WHERE d.kind IN ('SALE','SALE_RETURN');
