CREATE TABLE held_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    held_id BIGINT NOT NULL REFERENCES held_sales(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity DECIMAL(24,6) NOT NULL CHECK(quantity>0),
    price DECIMAL(24,6) NOT NULL CHECK(price>=0),
    discount_value DECIMAL(24,6) NOT NULL DEFAULT 0,
    discount_percent BOOLEAN NOT NULL DEFAULT FALSE,
    note VARCHAR(1000)
);

CREATE TABLE stock_counts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number VARCHAR(40) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    posted_document_id BIGINT REFERENCES documents(id)
);

CREATE TABLE stock_count_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    count_id BIGINT NOT NULL REFERENCES stock_counts(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    expected DECIMAL(24,6) NOT NULL,
    counted DECIMAL(24,6) NOT NULL CHECK(counted>=0),
    UNIQUE(count_id,product_id)
);

CREATE TABLE period_locks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    locked_by BIGINT NOT NULL REFERENCES users(id),
    reason VARCHAR(1000) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK(start_date<=end_date)
);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_key VARCHAR(100) NOT NULL UNIQUE,
    kind VARCHAR(40) NOT NULL,
    entity_id BIGINT,
    message VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE notification_reads (
    notification_id BIGINT NOT NULL REFERENCES notifications(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    PRIMARY KEY(notification_id,user_id)
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
