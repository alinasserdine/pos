    entity_id BIGINT,
    old_summary VARCHAR(2000),
    new_summary VARCHAR(2000),
    reason VARCHAR(1000),
    approved_by BIGINT REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

