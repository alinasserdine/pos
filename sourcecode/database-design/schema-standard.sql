    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_products_category_id FOREIGN KEY (category_id) REFERENCES categories(id),
    CONSTRAINT fk_products_unit_id FOREIGN KEY (unit_id) REFERENCES units(id),
    CONSTRAINT fk_products_tax_id FOREIGN KEY (tax_id) REFERENCES tax_rates(id),
    CONSTRAINT fk_products_preferred_supplier_id FOREIGN KEY (preferred_supplier_id) REFERENCES parties(id),
    CONSTRAINT fk_products_parent_product_id FOREIGN KEY (parent_product_id) REFERENCES products(id)
);

CREATE TABLE product_barcodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    barcode VARCHAR(100) NOT NULL UNIQUE,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_product_barcodes_product_id FOREIGN KEY (product_id) REFERENCES products(id)
);

CREATE TABLE price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    old_price DECIMAL(24,6) NOT NULL,
    new_price DECIMAL(24,6) NOT NULL,
    old_cost DECIMAL(24,6) NOT NULL,
