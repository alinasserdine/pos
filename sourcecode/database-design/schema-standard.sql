CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    document_id BIGINT NOT NULL,
    document_line_id BIGINT,
    movement_type VARCHAR(40) NOT NULL,
    quantity DECIMAL(24,6) NOT NULL,
    before_qty DECIMAL(24,6) NOT NULL,
    after_qty DECIMAL(24,6) NOT NULL,
    cost_value DECIMAL(24,6) NOT NULL,
    reason VARCHAR(1000),
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK(after_qty=before_qty+quantity),
    CONSTRAINT fk_stock_movements_product_id FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_stock_movements_document_id FOREIGN KEY (document_id) REFERENCES documents(id),
    CONSTRAINT fk_stock_movements_document_line_id FOREIGN KEY (document_line_id) REFERENCES document_lines(id),
    CONSTRAINT fk_stock_movements_user_id FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE cost_layers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    movement_id BIGINT NOT NULL,
    original_quantity DECIMAL(24,6) NOT NULL CHECK(original_quantity>0),
    remaining_qty DECIMAL(24,6) NOT NULL CHECK(remaining_qty>=0),
    original_value DECIMAL(24,6) NOT NULL CHECK(original_value>=0),
    remaining_value DECIMAL(24,6) NOT NULL CHECK(remaining_value>=0),
    acquired_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
