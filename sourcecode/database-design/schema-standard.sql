CREATE TABLE damaged_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    source_document_line_id BIGINT NOT NULL UNIQUE,
    quantity DECIMAL(24,6) NOT NULL CHECK(quantity>0),
    remaining_quantity DECIMAL(24,6) NOT NULL CHECK(remaining_quantity>=0),
    historical_cost DECIMAL(24,6) NOT NULL CHECK(historical_cost>=0),
    carrying_value DECIMAL(24,6) NOT NULL CHECK(carrying_value>=0),
    status VARCHAR(12) NOT NULL CHECK(status IN ('PENDING','VALUED','DISPOSED')),
    CHECK(remaining_quantity<=quantity),
    CONSTRAINT fk_damaged_inventory_product_id FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_damaged_inventory_source_document_line_id FOREIGN KEY (source_document_line_id) REFERENCES document_lines(id)
);

